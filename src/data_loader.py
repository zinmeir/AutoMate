"""Loading and validating transaction data, with a synthetic fallback."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from .config import RAW_DATA_PATH, REQUIRED_COLUMNS, SYNTHETIC_NOTICE, SYNTHETIC_N_TRANSACTIONS, SYNTHETIC_SEED
from .synthetic_data import generate_raw_transactions


class DataValidationError(ValueError):
    """Raised when a transaction table does not satisfy the expected schema."""


@dataclass(frozen=True)
class Provenance:
    source: str          # human-readable origin
    is_synthetic: bool
    used_fallback: bool  # True when the file was missing/unreadable and data was regenerated
    note: str


def validate_schema(df: pd.DataFrame) -> None:
    """Check that the table is a non-empty long-format transaction table."""
    if not isinstance(df, pd.DataFrame):
        raise DataValidationError("Expected a pandas DataFrame.")
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise DataValidationError(f"Missing required column(s): {', '.join(missing)}. "
                                  f"Expected at least: {', '.join(REQUIRED_COLUMNS)}.")
    if df.empty:
        raise DataValidationError("The transaction table contains no rows.")


def load_transactions(path: str | Path | None = None, allow_fallback: bool = True) -> tuple[pd.DataFrame, Provenance]:
    """Load the raw transaction file.

    If the file is missing, unreadable or has the wrong schema and
    ``allow_fallback`` is true, the deterministic synthetic dataset is generated
    in memory instead so the application can always start.
    """
    path = Path(path) if path is not None else RAW_DATA_PATH
    problem: str | None = None
    if path.exists():
        try:
            df = pd.read_csv(path, dtype={"transaction_id": "string", "item": "string"})
            validate_schema(df)
            return df, Provenance(source=f"{path.name} (synthetic, generated by scripts/prepare_dataset.py)",
                                  is_synthetic=True, used_fallback=False, note=SYNTHETIC_NOTICE)
        except (DataValidationError, pd.errors.ParserError, pd.errors.EmptyDataError, UnicodeDecodeError, ValueError) as exc:
            problem = f"{path.name} could not be used ({exc})"
    else:
        problem = f"{path.name} was not found"
    if not allow_fallback:
        raise DataValidationError(problem)
    df = generate_raw_transactions(SYNTHETIC_N_TRANSACTIONS, SYNTHETIC_SEED)
    return df, Provenance(source="in-memory synthetic generator (fallback)", is_synthetic=True, used_fallback=True,
                          note=f"{problem}; regenerated the synthetic dataset in memory. {SYNTHETIC_NOTICE}")
